// 卡车驾驶室钣金：略方、棱线硬，但不至于像块砖
const hull = (sta, color, o = {}) => hullBase(sta, color, {
  ...o,
  pow: Math.max(o.pow ?? 0, 10),
  tumble: Math.min(o.tumble ?? 0.02, 0.035),
  tuck: Math.min(o.tuck ?? 0.02, 0.035),
  crease: o.crease ?? 0.978
});

const STEEL = 0x9aa4ad;
const DARK = 0x33383f;
const RUB = 0x1b1b1b;

// 梯身：沿 YZ 平面斜向上伸展的一段（两根边梁 + 一排横档）
// ang > 0 表示朝车头方向抬起；off 是沿梯身法向的偏移，用来做出套叠层次
function ladderRun({ y, z, ang, len, start = 0, halfW = 0.4, thick = 0.16, off = 0, color = STEEL, step = 0.34 }) {
  const dy = Math.sin(ang);
  const dz = Math.cos(ang);
  const y0 = y + Math.cos(ang) * off + dy * start;
  const z0 = z - Math.sin(ang) * off + dz * start;
  const cy = y0 + dy * (len / 2);
  const cz = z0 + dz * (len / 2);
  const out = [-1, 1].map((sx) =>
    box(0.1, thick, len, color, sx * halfW, cy, cz, { r: [-ang, 0, 0], metal: 0.8, rough: 0.28 }));
  const n = Math.max(2, Math.round(len / step));
  for (let i = 1; i < n; i++) {
    const t = (i / n) * len;
    out.push(box(halfW * 2, 0.05, 0.08, color, 0, y0 + dy * t, z0 + dz * t,
      { r: [-ang, 0, 0], metal: 0.8, rough: 0.28 }));
  }
  return out;
}

