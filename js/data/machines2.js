// 工程机械外壳：略方的截面 + 硬折角，和 machines.js 保持一致
const hull = (sta, color, o = {}) => hullBase(sta, color, {
  ...o,
  pow: Math.max(o.pow ?? 0, 10),
  tumble: Math.min(o.tumble ?? 0.02, 0.035),
  tuck: Math.min(o.tuck ?? 0.02, 0.035),
  crease: o.crease ?? 0.978
});

// 在 YZ 平面内连接两点的梁（挖掘臂、油缸都用它）
function beamY(a, b, w, h, color, o = {}) {
  const dy = b[1] - a[1];
  const dz = b[2] - a[2];
  const len = Math.hypot(dy, dz);
  const th = Math.atan2(-dy, dz);
  return box(w, h, len, color, (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2,
    { r: [th, 0, 0], metal: 0.25, rough: 0.55, ...o });
}

// 液压油缸：缸筒 + 活塞杆，自动对齐方向
function strut(a, b, r1 = 0.07, r2 = 0.04, c1 = 0x3a3f45, c2 = 0xdde3e8) {
  const dy = b[1] - a[1];
  const dz = b[2] - a[2];
  const len = Math.hypot(dy, dz) || 1;
  const th = Math.atan2(dz, dy);
  const at = (t) => [a[0] + (b[0] - a[0]) * t, a[1] + dy * t, a[2] + dz * t];
  const p1 = at(0.28);
  const p2 = at(0.72);
  return [
    cyl(r1, r1, len * 0.6, c1, p1[0], p1[1], p1[2], { r: [th, 0, 0], seg: 14, metal: 0.3, rough: 0.5 }),
    cyl(r2, r2, len * 0.56, c2, p2[0], p2[1], p2[2], { r: [th, 0, 0], seg: 12, metal: 0.8, rough: 0.2 })
  ];
}

