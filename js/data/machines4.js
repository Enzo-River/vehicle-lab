// 工程机械的钣金/铸造外壳：略方、棱线硬，但保留铸造圆角
const hull = (sta, color, o = {}) => hullBase(sta, color, {
  ...o,
  pow: Math.max(o.pow ?? 0, 10),
  tumble: Math.min(o.tumble ?? 0.02, 0.035),
  tuck: Math.min(o.tuck ?? 0.02, 0.035),
  crease: o.crease ?? 0.978
});

const DK = 0x33383f;
const STEEL = 0x9aa4ad;
const GR = 0xf0b81d;
const GR_D = 0xc99612;

// 把一组零件的 z 坐标整体平移，履带/轮组复用同一份几何
const shiftZ = (arr, dz) => arr.map((pc) => ({ ...pc, p: [pc.p[0], pc.p[1], pc.p[2] + dz] }));

// YZ 平面内的斜杆：a、b 两点（x 保持一致）
function beamYZ(a, b, w = 0.07, color = STEEL, o = {}) {
  const dy = b[1] - a[1];
  const dz = b[2] - a[2];
  const len = Math.hypot(dy, dz) || 0.001;
  const th = Math.atan2(-dy / len, dz / len);
  return box(w, w, len, color, (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2,
    { r: [th, 0, 0], metal: 0.7, rough: 0.35, ...o });
}

