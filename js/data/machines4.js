// 桁架臂：四根主弦 + 横撑 + 侧面斜撑
function latticeBoom({ y, z, ang, len, halfW = 0.44, halfH = 0.36, step = 1.15, color = CC }) {
  const dy = Math.sin(ang);
  const dz = Math.cos(ang);
  const ny = Math.cos(ang);
  const nz = -Math.sin(ang);
  const cy = y + dy * (len / 2);
  const cz = z + dz * (len / 2);
  const out = [];
  [-1, 1].forEach((sx) => [-1, 1].forEach((sy) => {
    out.push(box(0.09, 0.09, len, color, sx * halfW, cy + sy * halfH * ny, cz + sy * halfH * nz,
      { r: [-ang, 0, 0], metal: 0.6, rough: 0.42 }));
  }));
  const n = Math.max(3, Math.round(len / step));
  for (let i = 1; i < n; i++) {
    const t = (i * len) / n;
    const py = y + dy * t;
    const pz = z + dz * t;
    [-1, 1].forEach((sy) => {
      out.push(box(halfW * 2, 0.07, 0.07, color, 0, py + sy * halfH * ny, pz + sy * halfH * nz,
        { r: [-ang, 0, 0], metal: 0.6, rough: 0.42 }));
    });
  }
  for (let i = 0; i < n; i++) {
    const t0 = (i * len) / n;
    const t1 = ((i + 1) * len) / n;
    const a1 = i % 2 === 0 ? 1 : -1;
    [-1, 1].forEach((sx) => {
      out.push(beamYZ(
        [sx * halfW, y + dy * t0 + a1 * halfH * ny, z + dz * t0 + a1 * halfH * nz],
        [sx * halfW, y + dy * t1 - a1 * halfH * ny, z + dz * t1 - a1 * halfH * nz],
        0.06, color, { metal: 0.6, rough: 0.42 }
      ));
    });
  }
  return out;
}

