// 挂车后轮组：两根车轴四只宽胎，和悬架一起分担货厢重量
function bogiePart({ id, name, axles, desc, tip }) {
  const pieces = [];
  axles.forEach((dz) => {
    // 车轴
    pieces.push(cyl(0.11, 0.11, 2.02, 0x3a3f45, 0, R, dz,
      { r: [0, 0, Math.PI / 2], seg: 18, metal: 0.45, rough: 0.45 }));
    [-1, 1].forEach((sx) => {
      pieces.push(...wheelSet(R, 0.62, 0xc9ced4, 6)
        .map((p) => ({ ...p, p: [p.p[0] + sx * 0.99, p.p[1] + R, p.p[2] + dz] })));
      // 轮眉与挡泥板
      pieces.push(arch(0.66, 0.08, 0x24262b, sx * 1.2, R, dz));
      pieces.push(box(0.07, 0.52, 0.6, 0x24262b, sx * 1.22, R + 0.28, dz + 0.52));
      // 钢板弹簧、吊耳与气囊
      pieces.push(box(0.1, 0.1, 1.72, 0x2b2f34, sx * 0.58, R + 0.04, dz, { metal: 0.5, rough: 0.5 }));
      pieces.push(box(0.16, 0.26, 0.14, 0x33383f, sx * 0.58, R + 0.26, dz + 0.78));
      pieces.push(box(0.16, 0.26, 0.14, 0x33383f, sx * 0.58, R + 0.26, dz - 0.78));
      pieces.push(cyl(0.14, 0.14, 0.26, 0x181818, sx * 0.58, R + 0.46, dz, { seg: 16 }));
    });
  });
  return {
    id, name,
    desc, tip,
    color: '#2b2b2b',
    pos: [0, 0, (axles[0] + axles[axles.length - 1]) / 2],
    off: [0, 1.2, -1.6],
    pieces: pieces.map((p) => ({ ...p, p: [p.p[0], p.p[1], p.p[2] - (axles[0] + axles[axles.length - 1]) / 2] }))
  };
}

