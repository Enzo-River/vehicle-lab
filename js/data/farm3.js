// 沿 a→b 的杆件：长度与绕 X 的倾角自动计算
const beam = (a, b, w, d, color, o = {}) => {
  const dy = b[1] - a[1];
  const dz = b[2] - a[2];
  return box(w, Math.hypot(dy, dz), d, color,
    (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2,
    { r: [Math.atan2(dz, dy), 0, 0], ...o });
};

