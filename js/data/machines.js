// 履带板：沿「跑道形」路径铺一圈，前后端是半圆，像真正的履带链
// halfLen 是直线段半长，r 是端部半径（也等于履带中心线高度），底部刚好落在 y=0
function trackLoop(o = {}) {
  const { halfLen = 1.35, r = 0.34, w = 0.62, count = 26, color = 0x26282c } = o;
  const straight = 2 * halfLen;
  const arc = Math.PI * r;
  const P = 2 * straight + 2 * arc;
  const step = P / count;
  const out = [];
  for (let i = 0; i < count; i++) {
    const s = i * step + step / 2;
    let py, pz, th;
    if (s < straight) {
      // 上直线段：从车头往车尾
      py = r; pz = halfLen - s; th = 0;
    } else if (s < straight + arc) {
      // 车尾半圆
      const phi = (s - straight) / r;
      py = r * Math.cos(phi); pz = -halfLen - r * Math.sin(phi); th = -phi;
    } else if (s < 2 * straight + arc) {
      // 下直线段：贴着地面
      py = -r; pz = -halfLen + (s - straight - arc); th = Math.PI;
    } else {
      // 车头半圆
      const phi = (s - 2 * straight - arc) / r;
      py = -r * Math.cos(phi); pz = halfLen + r * Math.sin(phi); th = Math.PI - phi;
    }
    // 履带板
    out.push(box(w, 0.07, step * 1.14, color, 0, py, pz, { r: [th, 0, 0], rough: 0.94, metal: 0.06 }));
    // 履带板外侧的导向筋
    out.push(box(w * 0.2, 0.07, step * 0.5, 0x15171a, 0,
      py + Math.cos(th) * 0.065, pz + Math.sin(th) * 0.065,
      { r: [th, 0, 0], rough: 0.96, metal: 0.04 }));
  }
  return out;
}

// 履带内部：履带架 + 驱动轮/引导轮 + 支重轮 + 托链轮
function trackInternals(o = {}) {
  const { halfLen = 1.35, r = 0.34, w = 0.62, road = 4 } = o;
  const out = [
    box(w * 0.6, r * 1.0, halfLen * 1.62, 0x3a3f45, 0, 0, 0, { rough: 0.82, metal: 0.18 }),
    // 驱动轮（后）与引导轮（前）
    cyl(r * 0.8, r * 0.8, w * 0.62, 0x2b2f34, 0, 0, halfLen, { r: [0, 0, Math.PI / 2], seg: 20, rough: 0.86, metal: 0.1 }),
    cyl(r * 0.8, r * 0.8, w * 0.62, 0x2b2f34, 0, 0, -halfLen, { r: [0, 0, Math.PI / 2], seg: 20, rough: 0.86, metal: 0.1 }),
    cyl(r * 0.4, r * 0.4, w * 0.66, 0x5c646b, 0, 0, halfLen, { r: [0, 0, Math.PI / 2], seg: 16, metal: 0.3, rough: 0.55 }),
    cyl(r * 0.4, r * 0.4, w * 0.66, 0x5c646b, 0, 0, -halfLen, { r: [0, 0, Math.PI / 2], seg: 16, metal: 0.3, rough: 0.55 })
  ];
  for (let i = 0; i < road; i++) {
    const t = road === 1 ? 0.5 : i / (road - 1);
    const z = -halfLen * 0.74 + t * halfLen * 1.48;
    out.push(cyl(r * 0.33, r * 0.33, w * 0.6, 0x4a4a4a, 0, -r * 0.52, z,
      { r: [0, 0, Math.PI / 2], seg: 14, metal: 0.3, rough: 0.6 }));
  }
  // 托链轮
  out.push(cyl(r * 0.2, r * 0.2, w * 0.52, 0x4a4a4a, 0, r * 0.62, halfLen * 0.42, { r: [0, 0, Math.PI / 2], seg: 12, metal: 0.3, rough: 0.6 }));
  out.push(cyl(r * 0.2, r * 0.2, w * 0.52, 0x4a4a4a, 0, r * 0.62, -halfLen * 0.42, { r: [0, 0, Math.PI / 2], seg: 12, metal: 0.3, rough: 0.6 }));
  return out;
}

// 液压油缸：从 a 到 b 的一段缸筒 + 一段活塞杆，自动对齐方向
function strut(a, b, r1 = 0.09, r2 = 0.05, c1 = 0x3a3f45, c2 = 0xdde3e8) {
  const dy = b[1] - a[1];
  const dz = b[2] - a[2];
  const len = Math.hypot(dy, dz) || 1;
  const th = Math.atan2(dz, dy);
  const at = (t) => [a[0] + (b[0] - a[0]) * t, a[1] + dy * t, a[2] + dz * t];
  const p1 = at(0.28);
  const p2 = at(0.72);
  return [
    cyl(r1, r1, len * 0.62, c1, p1[0], p1[1], p1[2], { r: [th, 0, 0], seg: 14, metal: 0.3, rough: 0.5 }),
    cyl(r2, r2, len * 0.56, c2, p2[0], p2[1], p2[2], { r: [th, 0, 0], seg: 12, metal: 0.8, rough: 0.2 })
  ];
}

