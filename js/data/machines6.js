// 沿 YZ 平面 a→b 的杆件（臂、斗杆）
const beam = (a, b, w, d, color, o = {}) => {
  const dy = b[1] - a[1];
  const dz = b[2] - a[2];
  return box(w, Math.hypot(dy, dz), d, color,
    (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2,
    { r: [Math.atan2(dz, dy), 0, 0], ...o });
};

// 沿 X-Y 平面 a→b 的杆件（侧伸臂）
const beamX = (a, b, w, d, color, o = {}) => {
  const dx = b[0] - a[0];
  const dy = b[1] - a[1];
  return box(w, Math.hypot(dx, dy), d, color,
    (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, (a[2] + b[2]) / 2,
    { r: [0, 0, Math.atan2(-dx, dy)], ...o });
};

